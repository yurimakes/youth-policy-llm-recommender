def decode_code(field_name: str, code: str | None) -> str | None:
    if code is None:
        return None

    normalized_field_name = _FIELD_ALIASES.get(field_name.strip(), field_name.strip())
    normalized_code = code.strip()
    if not normalized_code:
        return None

    return CODEBOOKS.get(normalized_field_name, {}).get(normalized_code)


def get_codebook(field_name: str) -> dict[str, str]:
    normalized_field_name = _FIELD_ALIASES.get(field_name.strip(), field_name.strip())
    return dict(CODEBOOKS.get(normalized_field_name, {}))
